// words are what the two parties agreed to, and a redesign must not change them.
// New contracts are built by ./contract.js (data.template === 'sale-v2').

const { BRAND_LOGO_URL } = require('../constants');
const escHtml = v => String(v ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

